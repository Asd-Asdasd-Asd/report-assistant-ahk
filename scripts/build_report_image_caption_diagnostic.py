#!/usr/bin/env python3
"""Build the single-file report image caption migration diagnostic."""

from __future__ import annotations

import argparse
from pathlib import Path

try:
    from scripts import ahk_bundle
except ModuleNotFoundError:  # executed directly from scripts/
    import ahk_bundle


ROOT = ahk_bundle.ROOT
DIRECTIVES = ahk_bundle.HARNESS_DIRECTIVES
read_component = ahk_bundle.read_component
OUTPUT = ROOT / "tests/windows/generated/report_image_caption_migration_diagnostic_standalone.ahk"

COMPONENTS = (
    "src/Lib/UIA.ahk",
    "tests/windows/report_image_caption_migration_diagnostic.ahk",
)

HEADER = (
    '; Generated single-file field diagnostic.',
    '; Edit the source components and rebuild; do not edit this file.',
    '; Does not click, paste, scroll, activate another window, or persist copied text.',
    ';@Ahk2Exe-SetFileVersion 1.1.0.0',
    ';@Ahk2Exe-SetProductVersion 1.1.0',
    ';@Ahk2Exe-SetName MedEx Report Image Caption Diagnostic',
)

UIA_STANDALONE_ENTRYPOINT = ahk_bundle.UIA_STANDALONE_ENTRYPOINT


def build_diagnostic_text(root: Path = ROOT) -> str:
    return ahk_bundle.bundle(
        HEADER,
        COMPONENTS,
        root=root,
        label="diagnostic",
        missing_message="Missing diagnostic component",
    )


def write_diagnostic(output: Path = OUTPUT) -> None:
    ahk_bundle.write_bundle(build_diagnostic_text(), output)


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate the standalone report image caption diagnostic.")
    parser.add_argument(
        "--output",
        type=Path,
        default=OUTPUT,
        help="Destination for the generated standalone AHK.",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    write_diagnostic(args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
